const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { registry } = require('./prepare.cjs');
const context = { window: {} };
vm.runInNewContext(fs.readFileSync(path.join(__dirname, '../search.js'), 'utf8'), context);
const { stores } = registry();
const names = (query, selection = stores) => Array.from(context.window.searchStores(selection, query), store => store.slug);
assert.equal(names('').length, stores.length);
assert.equal(names('  ').length, stores.length);
assert.deepEqual(names('BURGER'), ['ino-burger']);
assert.deepEqual(names('midho prive'), ['midho-prive']);
assert.deepEqual(names('  maison   allure  '), ['maison-allure']);
assert.deepEqual(names("sallon d'or"), ['sallon-dor']);
assert.deepEqual(names('sallon d’or'), ['sallon-dor']);
assert.deepEqual(names('not a real store'), []);
assert.deepEqual(names('<img src=x onerror=alert(1)>'), []);
assert.deepEqual(names('midho', stores.filter(store => store.category === 'clothing-store')), []);
assert.deepEqual(names('sallon', stores.filter(store => store.category === 'home-goods')), ['sallon-dor']);
assert.deepEqual(names('', []), []);
console.log('PASS search: case, accents, apostrophes, whitespace, no results and category scope.');
